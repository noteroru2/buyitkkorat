function countThaiWords(text) {
  const segmenter = new Intl.Segmenter("th", { granularity: "word" });
  let count = 0;
  for (const { segment, isWordLike } of segmenter.segment(text)) {
    if (isWordLike && segment.trim()) count += 1;
  }
  return count;
}

