function yamlEscape(s) {
  return s.replace(/"/g, '\\"').replace(/\n/g, " ");
}

function buildFaq(items) {
  return items
    .map(
      (f) =>
        `  - question: "${yamlEscape(f.q)}"\n    answer: "${yamlEscape(f.a)}"`,
    )
    .join("\n");
}

function buildFile(page) {
  const common = page.skipCommon
    ? []
    : [processBlock, priceBlock, koratBlock, refuseBlock];
  const minWords = page.minWords ?? 1800;
  let body = [...page.sections, ...common].join("\n\n");
  let words = countThaiWords(body);
  let extraIdx = 0;
  const extras = page.extras ?? [];
  while (words < minWords && extraIdx < extras.length) {
    body += "\n\n" + extras[extraIdx++];
    words = countThaiWords(body);
  }
  while (words < minWords) {
    body += "\n\n" + genericExtra(extraIdx++, page.h1);
    words = countThaiWords(body);
  }

  const related = (page.relatedPages ?? [])
    .map((s) => `  - "${s}"`)
    .join("\n");

  const fm = `---
title: "${yamlEscape(page.title)}"
description: "${yamlEscape(page.description)}"
h1: "${yamlEscape(page.h1)}"
slug: "${page.slug}"
category: "${page.category}"
intent: "${page.intent}"
excerpt: "${yamlEscape(page.excerpt)}"
publishedDate: 2026-01-15
updatedDate: 2026-07-14
featured: ${page.featured ?? false}
indexable: true
ogImage: "/og/default.png"
relatedPages:
${related}
serviceArea: "นครราชสีมา"
faq:
${buildFaq(page.faq)}
author: "${BRAND}"
reviewer: "${BRAND}"${page.productFocus ? `\nproductFocus: "${page.productFocus}"` : ""}${page.illustration ? `\nillustration: "${page.illustration}"` : ""}
---

${body}
`;

  return { fm, words };
}

