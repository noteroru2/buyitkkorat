#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=(p)=>JSON.parse(fs.readFileSync(path.join(root,p),'utf8'));
const cfg=read('src/config/index-350-w5-observation-gate.json');
const release=read('src/config/index-350-w5-release.json');
const prod=read('src/config/index-350-w5-production-gate.json');
const arch=read('src/config/site-architecture.json');
const local=read('src/config/local-area-release.json');
const errors=[];
const live=arch.routes.filter((r)=>r.kind==='LIVE');
const indexable=live.filter((r)=>r.indexState==='INDEX');
if(live.length<cfg.meta.expectedLiveRoutes)errors.push(`live ${live.length} < historical W5 minimum ${cfg.meta.expectedLiveRoutes}`);
if(indexable.length<cfg.meta.expectedIndexableRoutes)errors.push(`indexable ${indexable.length} < historical W5 minimum ${cfg.meta.expectedIndexableRoutes}`);
if(live.length-indexable.length!==cfg.meta.expectedNoindexRoutes)errors.push(`noindex ${live.length-indexable.length} != ${cfg.meta.expectedNoindexRoutes}`);
if(cfg.meta.observedUrls.length!==40||new Set(cfg.meta.observedUrls).size!==40)errors.push('Observed URL count/uniqueness must remain 40');
const expectedTypes={CONDITION:5,B2B:20,LOCAL:15};
const expectedClusters={NOTEBOOK:1,MOBILE:2,CAMERA:1,GAMING:1,B2B:20,LOCATION:15};
if(cfg.meta.groupMix?.D_CONDITION!==5||cfg.meta.groupMix?.E_B2B!==20||cfg.meta.groupMix?.F_LOCAL!==15)errors.push('W5 group mix changed');
for(const [k,v] of Object.entries(expectedClusters))if(cfg.meta.clusterMix?.[k]!==v)errors.push(`Cluster ${k} ${cfg.meta.clusterMix?.[k]} != ${v}`);
if(cfg.meta.automaticW6!==false||cfg.meta.w6LockedByDefault!==true)errors.push('W6 safety lock changed');
if(cfg.meta.releaseBasis!=='MANUAL_APPROVAL_OVERRIDE')errors.push('W5 release-basis disclosure changed');
if(cfg.meta.realW4PerformanceAttested!==false)errors.push('Historical W4 performance attestation was rewritten');
if(cfg.thresholds.minimumFinalizedDays<7)errors.push('Finalized date gate weakened below 7 days');
if(cfg.thresholds.minimumVisibleW5Pages<10)errors.push('Total visibility gate weakened');
if(cfg.thresholds.minimumIndexedW5Pages<32)errors.push('Total indexation gate weakened');
const visibleTypeMin={CONDITION:1,B2B:5,LOCAL:4};
const indexedTypeMin={CONDITION:4,B2B:16,LOCAL:12};
for(const [k,v] of Object.entries(visibleTypeMin))if((cfg.thresholds.minimumVisibleByType?.[k]??0)<v)errors.push(`Visibility type gate weakened: ${k}`);
for(const [k,v] of Object.entries(indexedTypeMin))if((cfg.thresholds.minimumIndexedByType?.[k]??0)<v)errors.push(`Indexation type gate weakened: ${k}`);
if((cfg.thresholds.minimumVisibleByCluster?.B2B??0)<5)errors.push('B2B visibility gate weakened');
if((cfg.thresholds.minimumVisibleByCluster?.LOCATION??0)<4)errors.push('Local visibility gate weakened');
if((cfg.thresholds.minimumIndexedByCluster?.B2B??0)<16)errors.push('B2B indexation gate weakened');
if((cfg.thresholds.minimumIndexedByCluster?.LOCATION??0)<12)errors.push('Local indexation gate weakened');
const condClusters=['NOTEBOOK','MOBILE','CAMERA','GAMING'];
if(JSON.stringify(cfg.thresholds.conditionClusters)!==JSON.stringify(condClusters))errors.push('Condition-cluster breadth list changed');
if(cfg.thresholds.minimumVisibleConditionClusters<2)errors.push('Condition visibility breadth gate weakened');
if(cfg.thresholds.minimumIndexedConditionClusters<3)errors.push('Condition indexation breadth gate weakened');
if(cfg.thresholds.maximumOwnershipReviewPairsForEligibility>4)errors.push('Ownership-review tolerance weakened above 4 pairs');
if(cfg.ownershipPairs.length!==40)errors.push(`Expected 40 ownership pairs, got ${cfg.ownershipPairs.length}`);
const flatProd=new Map();for(const g of prod.parentChildChecks)for(const c of g.children)flatProd.set(c,g.parent);
const countedTypes={CONDITION:0,B2B:0,LOCAL:0};
const countedClusters={NOTEBOOK:0,MOBILE:0,CAMERA:0,GAMING:0,B2B:0,LOCATION:0};
for(const pair of cfg.ownershipPairs){
  if(!cfg.meta.observedUrls.includes(pair.child))errors.push(`Pair child not W5: ${pair.child}`);
  if(!live.some((r)=>r.url===pair.parent))errors.push(`Pair parent not live: ${pair.parent}`);
  if(!(pair.nodeType in countedTypes))errors.push(`Unexpected node type: ${pair.child} ${pair.nodeType}`); else countedTypes[pair.nodeType]++;
  if(flatProd.get(pair.child)!==pair.parent)errors.push(`Production parent mismatch: ${pair.child}`);
  if(cfg.nodeTypeByUrl[pair.child]!==pair.nodeType)errors.push(`Type mapping mismatch: ${pair.child}`);
  if(cfg.clusterByUrl[pair.child]!==pair.cluster)errors.push(`Cluster mapping mismatch: ${pair.child}`);
  if(countedClusters[pair.cluster]===undefined)errors.push(`Unknown cluster ${pair.cluster}`); else countedClusters[pair.cluster]++;
}
for(const [k,v] of Object.entries(expectedTypes))if(countedTypes[k]!==v)errors.push(`Ownership type split ${k} ${countedTypes[k]} != ${v}`);
for(const [k,v] of Object.entries(expectedClusters))if(countedClusters[k]!==v)errors.push(`Ownership cluster split ${k} ${countedClusters[k]} != ${v}`);
for(const u of cfg.meta.observedUrls){
  if(!release.releasedUrls.includes(u))errors.push(`Observation URL not in W5 release: ${u}`);
  if(!prod.meta.releasedUrls.includes(u))errors.push(`Observation URL not in W5 production gate: ${u}`);
}
const localUrls=cfg.meta.observedUrls.filter((u)=>cfg.nodeTypeByUrl[u]==='LOCAL');
const registered=new Set((local.areas??[]).map((a)=>a.url));
for(const u of localUrls){if(!registered.has(u))errors.push(`W5 local observation URL missing from local-area registry: ${u}`);if(flatProd.get(u)!=='/พื้นที่')errors.push(`W5 local parent must be /พื้นที่: ${u}`);}
for(const [k,v] of Object.entries(release.localSafety??{}))if(v!==true)errors.push(`W5 local safety flag is not true: ${k}`);
if(!cfg.hardRules.some((x)=>x.includes('no fake branches')))errors.push('Observation hard rules lost local fake-branch safety');
for(const script of ['scripts/evaluate-index-350-w5-observation.mjs','scripts/validate-index-350-w5-observation-gate.mjs'])if(!fs.existsSync(path.join(root,script)))errors.push(`Missing ${script}`);
for(const file of ['docs/gsc/index350-w5-gsc-template.csv','docs/gsc/index350-w5-indexation-template.csv','APPLY_INDEX350_W5_OBSERVATION_GATE.md'])if(!fs.existsSync(path.join(root,file)))errors.push(`Missing ${file}`);
console.log('INDEX 350 — W5 OBSERVATION GATE VALIDATION');
console.log(`Live/indexable/noindex: ${live.length}/${indexable.length}/${live.length-indexable.length}`);
console.log(`Observed W5 URLs: ${cfg.meta.observedUrls.length}`);
console.log(`Type mix: ${Object.entries(countedTypes).map(([k,v])=>`${k} ${v}`).join(' | ')}`);
console.log(`Cluster mix: ${Object.entries(countedClusters).map(([k,v])=>`${k} ${v}`).join(' | ')}`);
console.log(`Ownership pairs: ${cfg.ownershipPairs.length}`);
console.log(`Finalized-day gate: ${cfg.thresholds.minimumFinalizedDays}`);
console.log(`Visibility gate: ${cfg.thresholds.minimumVisibleW5Pages}/40; type minima ${Object.entries(cfg.thresholds.minimumVisibleByType).map(([k,v])=>`${k} ${v}`).join(', ')}; B2B ${cfg.thresholds.minimumVisibleByCluster.B2B}; Local ${cfg.thresholds.minimumVisibleByCluster.LOCATION}; condition-cluster breadth ${cfg.thresholds.minimumVisibleConditionClusters}/${condClusters.length}`);
console.log(`Indexation gate: ${cfg.thresholds.minimumIndexedW5Pages}/40; type minima ${Object.entries(cfg.thresholds.minimumIndexedByType).map(([k,v])=>`${k} ${v}`).join(', ')}; B2B ${cfg.thresholds.minimumIndexedByCluster.B2B}; Local ${cfg.thresholds.minimumIndexedByCluster.LOCATION}; condition-cluster breadth ${cfg.thresholds.minimumIndexedConditionClusters}/${condClusters.length}`);
console.log(`Release basis: ${cfg.meta.releaseBasis}`);
console.log(`W6 locked: ${cfg.meta.w6LockedByDefault}`);
if(errors.length){for(const e of errors)console.error(`ERROR: ${e}`);console.error('VERDICT: FAIL');process.exitCode=1;}else console.log('VERDICT: PASS');
